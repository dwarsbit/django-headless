/**
 * Generate the TypeScript types of the exposed models from the OpenAPI
 * schema of Django Headless: an interface per model, and the `Models` map
 * that types a `DjangoRestClient`.
 */

export interface SchemaObject {
  $ref?: string;
  type?: string;
  format?: string;
  enum?: unknown[];
  nullable?: boolean;
  readOnly?: boolean;
  writeOnly?: boolean;
  description?: string;
  items?: SchemaObject;
  properties?: { [name: string]: SchemaObject };
  required?: string[];
  additionalProperties?: boolean | SchemaObject;
  oneOf?: SchemaObject[];
  anyOf?: SchemaObject[];
  allOf?: SchemaObject[];
}

interface Parameter {
  name: string;
  in: string;
  schema?: SchemaObject;
  "x-filter"?: boolean;
  "x-expandable"?: { [name: string]: { component: string; many: boolean } };
  description?: string;
}

interface Operation {
  operationId?: string;
  tags?: string[];
  parameters?: Parameter[];
  responses?: { [status: string]: { content?: { [mediaType: string]: { schema?: SchemaObject } } } };
}

export interface OpenAPIDocument {
  openapi?: string;
  info?: { title?: string; version?: string };
  paths?: { [path: string]: { [method: string]: Operation } };
  components?: { schemas?: { [name: string]: SchemaObject } };
}

export interface GenerateOptions {
  /** A comment line at the top of the file, after the generated notice. */
  header?: string;
}

interface Route {
  base: { [method: string]: Operation };
  detail: { [method: string]: Operation };
  lookups: { [field: string]: Operation };
}

interface ModelInfo {
  label: string;
  component: string | undefined;
  singleton: boolean;
  paginated: boolean;
  readOnly: boolean;
  id: string;
  filters: { [name: string]: string };
  lookups: { [name: string]: string };
  expandable: { [name: string]: { component: string; many: boolean } };
}

const METHODS = ["get", "post", "put", "patch", "delete"];

/** Generate the TypeScript source of the types of an OpenAPI schema of Django Headless. */
export function generate(document: OpenAPIDocument, options: GenerateOptions = {}): string {
  if (!document || typeof document !== "object" || !document.paths) {
    throw new Error("The schema has no paths. Is it the OpenAPI schema of Django Headless?");
  }

  const components = document.components?.schemas ?? {};
  const models = collectModels(document);

  if (models.length === 0) {
    throw new Error("The schema has no routes of exposed models.");
  }

  const componentLabels = new Map<string, string>();
  for (const model of models) {
    if (model.component && !componentLabels.has(model.component)) {
      componentLabels.set(model.component, model.label);
    }
  }

  const lines: string[] = [
    "// Generated by django-headless from the OpenAPI schema of the API. Do not edit this file:",
    "// run `django-headless generate` again when the exposed models change.",
  ];
  if (options.header) {
    lines.push(`// ${options.header}`);
  }
  lines.push("");

  const inputComponents = new Set(
    models.filter((model) => !model.readOnly && model.component).map((model) => model.component as string),
  );

  for (const name of Object.keys(components).sort()) {
    const schema = components[name] as SchemaObject;
    lines.push(...renderInterface(typeName(name), schema, "item"), "");

    if (inputComponents.has(name)) {
      lines.push(...renderInterface(`${typeName(name)}Input`, schema, "input"), "");
    }
  }

  lines.push("export type Models = {");
  for (const model of models) {
    lines.push(...renderModel(model, components, componentLabels).map((line) => `  ${line}`));
  }
  lines.push("};", "");

  return lines.join("\n");
}

function collectModels(document: OpenAPIDocument): ModelInfo[] {
  const routes = new Map<string, Route>();

  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const method of METHODS) {
      const operation = item[method];
      const label = operation?.tags?.[0];
      if (!operation || !label) {
        continue;
      }

      const index = path.lastIndexOf(`/${label}`);
      if (index === -1) {
        continue;
      }

      const rest = path.slice(index + label.length + 1);
      const route = routes.get(label) ?? { base: {}, detail: {}, lookups: {} };
      const lookup = /^\/by_(\w+)\/\{value\}$/.exec(rest);

      if (rest === "") {
        route.base[method] = operation;
      } else if (rest === "/{id}") {
        route.detail[method] = operation;
      } else if (lookup && method === "get") {
        route.lookups[lookup[1] as string] = operation;
      } else {
        continue;
      }

      routes.set(label, route);
    }
  }

  return [...routes.keys()].sort().map((label) => describeModel(label, routes.get(label) as Route));
}

function describeModel(label: string, route: Route): ModelInfo {
  const baseResponse = getResponseSchema(route.base.get);
  const detailResponse = getResponseSchema(route.detail.get);

  let component = refName(baseResponse?.$ref) ?? refName(detailResponse?.$ref);
  let singleton = false;
  let paginated = true;

  if (baseResponse?.$ref) {
    // A list route answers a list or the envelope; a singleton answers the object
    singleton = Object.keys(route.detail).length === 0;
  } else if (baseResponse?.type === "array") {
    paginated = false;
    component ??= refName(baseResponse.items?.$ref);
  } else if (baseResponse?.properties?.data) {
    component ??= refName(baseResponse.properties.data.items?.$ref);
  }

  const readOnly = singleton
    ? !route.base.put && !route.base.patch
    : !route.base.post && !route.detail.put && !route.detail.patch && !route.detail.delete;

  const idParameter = Object.values(route.detail)
    .flatMap((operation) => operation.parameters ?? [])
    .find((parameter) => parameter.in === "path" && parameter.name === "id");

  const filters: ModelInfo["filters"] = {};
  for (const parameter of route.base.get?.parameters ?? []) {
    if (parameter.in === "query" && isFilter(parameter)) {
      filters[parameter.name] = parameter.schema ? renderFilterType(parameter.schema) : "string";
    }
  }

  const lookups: ModelInfo["lookups"] = {};
  for (const [field, operation] of Object.entries(route.lookups)) {
    const value = operation.parameters?.find((parameter) => parameter.in === "path" && parameter.name === "value");
    lookups[field] = value?.schema ? renderType(value.schema) : "string";
  }

  const expandParameter = [route.base.get, route.detail.get]
    .flatMap((operation) => operation?.parameters ?? [])
    .find((parameter) => parameter.name === "expand" && parameter["x-expandable"]);

  return {
    label,
    component,
    singleton,
    paginated,
    readOnly,
    id: idParameter?.schema ? renderType(idParameter.schema) : "string | number",
    filters,
    lookups,
    expandable: expandParameter?.["x-expandable"] ?? {},
  };
}

/** The type of a filter value: a date can be passed as a Date. */
function renderFilterType(schema: SchemaObject): string {
  const type = renderType(schema);
  return schema.type === "string" && (schema.format === "date" || schema.format === "date-time")
    ? `${type} | Date`
    : type;
}

function isFilter(parameter: Parameter): boolean {
  if (parameter["x-filter"] !== undefined) {
    return parameter["x-filter"];
  }

  // Schemas without the x-filter extension describe each filter this way
  return Boolean(parameter.description?.startsWith("Filter on `"));
}

function getResponseSchema(operation: Operation | undefined): SchemaObject | undefined {
  const response = operation?.responses?.["200"];
  return response?.content?.["application/json"]?.schema;
}

function refName(ref: string | undefined): string | undefined {
  return ref?.startsWith("#/components/schemas/") ? ref.slice("#/components/schemas/".length) : undefined;
}

function renderModel(
  model: ModelInfo,
  components: { [name: string]: SchemaObject },
  componentLabels: Map<string, string>,
): string[] {
  const schema = model.component ? components[model.component] : undefined;
  const item = model.component && schema ? typeName(model.component) : "{ [key: string]: unknown }";
  const input = model.readOnly ? "never" : model.component && schema ? `${typeName(model.component)}Input` : item;

  const expandable: string[] = [];
  for (const [name, relation] of Object.entries(model.expandable)) {
    const target = componentLabels.get(relation.component);
    // A relation to a model that is not in the schema is left out
    if (!target) {
      continue;
    }

    const property = schema?.properties?.[name];
    const nullable = relation.many ? false : property ? Boolean(property.nullable) : true;
    expandable.push(
      `${propertyKey(name)}: { model: ${JSON.stringify(target)}; many: ${relation.many}; nullable: ${nullable} };`,
    );
  }

  return [
    `${JSON.stringify(model.label)}: {`,
    `  item: ${item};`,
    `  input: ${input};`,
    `  id: ${model.id};`,
    ...renderMembers("filters", model.filters),
    ...renderMembers("lookups", model.lookups),
    ...renderBlock("expandable", expandable),
    `  readOnly: ${model.readOnly};`,
    `  singleton: ${model.singleton};`,
    `  paginated: ${model.paginated};`,
    "};",
  ];
}

function renderMembers(name: string, members: { [name: string]: string }): string[] {
  return renderBlock(
    name,
    Object.entries(members).map(([key, type]) => `${propertyKey(key)}: ${type};`),
  );
}

function renderBlock(name: string, members: string[]): string[] {
  if (members.length === 0) {
    return [`  ${name}: {};`];
  }

  return [`  ${name}: {`, ...members.map((member) => `    ${member}`), "  };"];
}

function renderInterface(name: string, schema: SchemaObject, mode: "item" | "input"): string[] {
  const required = new Set(schema.required ?? []);
  const lines: string[] = [];

  if (schema.description) {
    lines.push(...renderComment(schema.description, ""));
  }
  lines.push(`export interface ${name} {`);

  for (const [property, propertySchema] of Object.entries(schema.properties ?? {})) {
    // A response leaves out write-only fields; a request leaves out read-only fields
    if (mode === "item" ? propertySchema.writeOnly : propertySchema.readOnly) {
      continue;
    }

    const comment = [propertySchema.description, describeFormat(propertySchema.format)]
      .filter(Boolean)
      .join(" ");
    if (comment) {
      lines.push(...renderComment(comment, "  "));
    }

    const optional = mode === "input" && !required.has(property) ? "?" : "";
    lines.push(`  ${propertyKey(property)}${optional}: ${renderType(propertySchema)};`);
  }

  lines.push("}");
  return lines;
}

// Formats that tell more than the TypeScript type; number formats such as int64 do not
const DESCRIBED_FORMATS = ["date", "date-time", "time", "uuid", "uri", "email", "decimal", "binary"];

function describeFormat(format: string | undefined): string | undefined {
  return format && DESCRIBED_FORMATS.includes(format) ? `Format: ${format}.` : undefined;
}

function renderComment(text: string, indent: string): string[] {
  const escaped = text.replace(/\*\//g, "*\\/");
  return [`${indent}/** ${escaped.replace(/\n+/g, " ")} */`];
}

/** The TypeScript type of a schema. */
export function renderType(schema: SchemaObject): string {
  const type = renderBaseType(schema);
  const hasNull = type === "unknown" || type.split(" | ").includes("null");
  return schema.nullable && !hasNull ? `${type} | null` : type;
}

function renderBaseType(schema: SchemaObject): string {
  if (schema.$ref) {
    const name = refName(schema.$ref);
    return name ? typeName(name) : "unknown";
  }

  if (schema.enum) {
    const literals = [...new Set(schema.enum.map((value) => JSON.stringify(value)))];
    return literals.length ? literals.join(" | ") : "never";
  }

  for (const [key, separator] of [
    ["oneOf", " | "],
    ["anyOf", " | "],
    ["allOf", " & "],
  ] as const) {
    const schemas = schema[key];
    if (schemas?.length) {
      return schemas.map((item) => wrap(renderType(item))).join(separator);
    }
  }

  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(schema.items ? renderType(schema.items) : "unknown")}[]`;
    case "object":
      return renderObjectType(schema);
    default:
      return schema.properties ? renderObjectType(schema) : "unknown";
  }
}

function renderObjectType(schema: SchemaObject): string {
  const required = new Set(schema.required ?? []);
  const members = Object.entries(schema.properties ?? {}).map(
    ([name, property]) => `${propertyKey(name)}${required.has(name) ? "" : "?"}: ${renderType(property)}`,
  );

  if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
    members.push(`[key: string]: ${renderType(schema.additionalProperties)}`);
  } else if (members.length === 0) {
    members.push("[key: string]: unknown");
  }

  return `{ ${members.join("; ")} }`;
}

function wrap(type: string): string {
  return /[|&]/.test(type) && !/^\{.*\}$/.test(type) ? `(${type})` : type;
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function typeName(name: string): string {
  const cleaned = name.replace(/[^\w$]/g, "_");
  return /^\d/.test(cleaned) ? `_${cleaned}` : cleaned;
}
